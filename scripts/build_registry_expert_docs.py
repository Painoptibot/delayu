def setup_styles(doc: Document) -> None:
    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(12)
    for level, size in [(1, 16), (2, 14), (3, 12)]:
        h = doc.styles[f"Heading {level}"]
        h.font.name = "Times New Roman"
        h.font.bold = True
        h.font.size = Pt(size)
        h.font.color.rgb = COLOR_PRIMARY


def add_footer(doc: Document, text: str) -> None:
    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(1.5)
    footer = section.footer
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.font.size = Pt(9)
    run.font.name = "Times New Roman"
    run.font.color.rgb = COLOR_MUTED


def add_title(doc: Document, title: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(title)
    r.bold = True
    r.font.size = Pt(16)
    r.font.name = "Times New Roman"
    r.font.color.rgb = COLOR_PRIMARY


def add_meta(doc: Document) -> None:
    lines = [
        f"Программное обеспечение: «{PRODUCT}» (линейка «{LINE}»)",
        f"Правообладатель: {VENDOR}",
        f"Версия: {VERSION}",
        f"Экземпляр для экспертизы: {SITE}",
        f"Публичная документация: {DOCS}",
    ]
    for line in lines:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(line)
        r.font.size = Pt(11)
        r.font.name = "Times New Roman"
        r.font.color.rgb = COLOR_MUTED
    doc.add_paragraph()


def add_p(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(1.25)
    p.paragraph_format.space_after = Pt(6)
    r = p.add_run(text)
    r.font.name = "Times New Roman"
    r.font.size = Pt(12)


def add_bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        r = p.add_run(item)
        r.font.name = "Times New Roman"
        r.font.size = Pt(12)


def add_numbered(doc: Document, items: list[str]) -> None:
    for item in items:
        p = doc.add_paragraph(style="List Number")
        r = p.add_run(item)
        r.font.name = "Times New Roman"
        r.font.size = Pt(12)


def new_doc(filename_stem_title: str) -> Document:
    doc = Document()
    setup_styles(doc)
    add_footer(doc, f"«{PRODUCT}» · {VENDOR} · v{VERSION} · документ для экспертной проверки")
    return doc


