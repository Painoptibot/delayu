def _norm(text: str) -> str:
    return (text or "").lower().replace("ё", "е")


def retrieve_articles(question: str, limit: int = 1) -> list[dict]:
    """Одна лучшая инструкция. Длинное совпадение важнее короткого."""
    query = _norm(question)
    padded = f" {query} "
    scored: list[tuple[int, dict]] = []
    for article in ARTICLES:
        score = 0
        for keyword in article["keywords"]:
            needle = _norm(keyword)
            if not needle or needle not in query:
                continue
            score += 4 + len(needle)
            if f" {needle}" in padded:
                score += 3
        if score:
            scored.append((score, article))
    scored.sort(key=lambda item: (-item[0], item[1]["id"]))
    found = [article for _, article in scored[:limit]]
    return found or [_GENERAL]


def answer_from_knowledge(question: str) -> str:
    articles = retrieve_articles(question, limit=1)
    text = articles[0]["answer"].strip()
    if articles[0]["id"] != "support":
        text += "\n\nЕсли этого недостаточно, нажмите «Передать специалисту ТП»."
    return text


