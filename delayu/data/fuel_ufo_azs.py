def _in_ufo(lat: float, lon: float) -> bool:
    return 43.0 <= lat <= 51.5 and 32.0 <= lon <= 49.5


def _generated() -> list[tuple]:
    rows: list[tuple] = []
    for slug, city, region, lat0, lon0, count in _TOWNS:
        for i in range(count):
            net_slug, network = _NETWORKS[i % len(_NETWORKS)]
            street = _STREETS[i % len(_STREETS)]
            house = 8 + (i * 11) % 180
            dlat = ((i * 7) % 11 - 5) * 0.0075
            dlon = ((i * 5) % 11 - 5) * 0.0105
            lat = round(lat0 + dlat, 6)
            lon = round(lon0 + dlon, 6)
            if not _in_ufo(lat, lon):
                lat, lon = lat0, lon0
            code = f"g-{slug}-{net_slug}-{i+1}"
            address = f"{street}, {house}"
            name = f"{network}, {city}, {street}"
            rows.append((code, name, network, address, region, city, lat, lon))
    return rows


